import AppKit
import ApplicationServices
import PromptDockCore

/// 粘贴流程（spec 8.2）：备份剪贴板 → 写入 → 激活原应用 → 模拟 ⌘V → 延时恢复剪贴板。
@MainActor
enum PasteService {

    static var isTrusted: Bool { AXIsProcessTrusted() }

    /// 弹出系统的辅助功能授权提示（仅在未授权时生效）。
    static func requestTrust() {
        let options = ["AXTrustedCheckOptionPrompt": true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
    }

    static func copy(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
    }

    /// 粘贴流程借用剪贴板的内容：标记为临时 + 自动生成（nspasteboard.org 约定），
    /// 剪贴板历史工具会跳过不记录，粘贴完成后剪贴板也会恢复。
    private static func copyTransient(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
    }

    /// - Parameter cursor: 粘贴后把光标移到占位符并选中（spec 8.6）；nil 表示不移动。
    static func paste(_ text: String, into target: NSRunningApplication?, settings: PasteSettings,
                      cursor: CursorPlacement? = nil) {
        let pb = NSPasteboard.general
        let snapshot = settings.restoreClipboard ? PasteboardSnapshot.capture(pb) : nil

        copyTransient(text)
        let changeCount = pb.changeCount

        target?.activate()

        Task { @MainActor in
            try? await Task.sleep(for: .milliseconds(80))
            postCommandV()
            Log.info("paste → \(target?.bundleIdentifier ?? "frontmost")，\(text.count) 字")
            if let cursor {
                // 等目标应用处理完粘贴再移动光标
                try? await Task.sleep(for: .milliseconds(80))
                moveCursor(cursor)
                Log.info("光标定位到占位符：左移 \(cursor.moveLeft)，选中 \(cursor.selectLength) 字")
            }

            guard let snapshot else { return }
            try? await Task.sleep(for: .milliseconds(settings.restoreDelayMs))
            // 期间若剪贴板被其他程序改动，则不覆盖
            if pb.changeCount == changeCount {
                snapshot.restore(to: pb)
            } else {
                Log.info("剪贴板已被其他程序改动，跳过恢复")
            }
        }
    }

    private static func moveCursor(_ cursor: CursorPlacement) {
        let left: CGKeyCode = 123   // kVK_LeftArrow
        for _ in 0..<cursor.moveLeft { KeyboardEvents.post(key: left) }
        for _ in 0..<cursor.selectLength { KeyboardEvents.post(key: left, flags: .maskShift) }
    }

    private static func postCommandV() {
        KeyboardEvents.postCommand(key: 9)   // kVK_ANSI_V
    }
}
